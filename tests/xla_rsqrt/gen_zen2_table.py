import ctypes, os
import numpy as np
here = os.path.dirname(os.path.abspath(__file__))
lib = ctypes.CDLL(os.path.join(here, "xla_rsqrt.dll"))
P = ctypes.POINTER(ctypes.c_uint32)
def est(bits):
    out = np.empty_like(bits)
    lib.rsqrt_many(bits.ctypes.data_as(P), out.ctypes.data_as(P), ctypes.c_long(len(bits)), 0, 0, 0)  # steps=0: raw estimate
    return out
idx = np.arange(4096, dtype=np.uint32)
tabs = {}
for name, e in (("odd", 127), ("even", 128)):
    x = (np.uint32(e) << np.uint32(23)) | (idx << np.uint32(11))
    y = est(x)
    assert ((y >> 23) == 126).all() and ((y & np.uint32(0x7ff)) == 0).all()
    tabs[name] = ((y >> 11) & np.uint32(0xfff)).astype(np.uint16)
def arr(name, t):
    rows = ["\t" + ", ".join("0x%03x" % v for v in t[i:i + 8]) + "," for i in range(0, len(t), 8)]
    return "static const uint16_t zen2_rsqrt_table_%s[4096] = {\n%s\n};\n" % (name, "\n".join(rows))
open(os.path.join(here, "..", "..", "guest", "ggml-rd", "rsqrt_zen2_table.h"), "w").write(
    "/* RSQRTPS on an AMD Ryzen 7 3800X (Zen 2): the 12-bit mantissa fraction of the result, indexed by the top 12\n"
    " * mantissa bits of the input. 'odd' is for an odd exponent field (input in [1,2) * 4^k), 'even' for an even one.\n"
    " * Generated by gen_zen2_table.py from the instruction itself. */\n#include <stdint.h>\n\n" + arr("odd", tabs["odd"]) + "\n" + arr("even", tabs["even"]))
print("header written")
