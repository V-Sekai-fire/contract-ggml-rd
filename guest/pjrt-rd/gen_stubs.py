#!/usr/bin/env python3
"""Write pjrt_rd_stubs.inc: one UNIMPLEMENTED stub for every entry of PJRT_Api."""
import re
import sys

header = sys.argv[1] if len(sys.argv) > 1 else "pjrt_c_api.h"
out_path = sys.argv[2] if len(sys.argv) > 2 else "pjrt_rd_stubs.inc"
text = open(header, encoding="utf-8").read()
body = re.search(r"typedef struct PJRT_Api \{(.*?)\} PJRT_Api;", text, re.S).group(1)
names = re.findall(r"_PJRT_API_STRUCT_FIELD\((\w+)\)", body)
void_returns = set(re.findall(r"typedef void (\w+)\(", text))
out = ["// Generated by gen_stubs.py from pjrt_c_api.h: one UNIMPLEMENTED stub per PJRT_Api entry.\n"]
for n in names:
    if n in void_returns:
        out.append("static void stub_%s(%s_Args *) {}\n" % (n, n))
    else:
        out.append('static PJRT_Error *stub_%s(%s_Args *) {\n\treturn unimplemented("%s");\n}\n' % (n, n, n))
out.append("\nstatic void fill_stubs(PJRT_Api *api) {\n")
for n in names:
    out.append("\tapi->%s = stub_%s;\n" % (n, n))
out.append("}\n")
open(out_path, "w", newline="\n").write("".join(out))
print(len(names), "entries,", len(void_returns & set(names)), "void")
